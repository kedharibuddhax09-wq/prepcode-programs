text=input("enter a string").lower()
vowels=(text.count("a")+text.count("e")+text.count("i")+text.count("o")+text.count("u"))
contonants = text.isalpha()
numbers = text.isdigit()
special_charecters=(len(text)-vowels-contonants-numbers)
print("no of vowels=",vowels)
print("no of contonants=",contonants)
print("no of numbers=",numbers)
print("no of special_charecters=",special_charecters)